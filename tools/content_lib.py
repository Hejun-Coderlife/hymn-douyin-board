def pick(options, salt):
    """从 options 里**确定性**地挑一条（纯哈希，管不住"连着两天别重样"）。

    **必须用 sha1，不能用 Python 的 hash()** —— 内置 hash() 对 str 加了随机盐，
    同一个进程内一致、换个进程就变，生成结果没法复现。
    sync_data 要求确定性输出，不然每次重新生成 602 个分片都算"改过"，
    仓库会每次胖 36MB。
    """
    h = int(hashlib.sha1(salt.encode("utf-8")).hexdigest()[:12], 16)
    return options[h % len(options)]


def offset(key):
    """把一个字符串（门店编号）折成一个稳定的整数，用来给轮换起点错位。"""
    return int(hashlib.sha1(key.encode("utf-8")).hexdigest()[:8], 16)


def rot(options, n):
    """按序号**轮换**着取，而不是哈希随机取。

    为什么不用 pick()：纯哈希挑，同一家店连着两天很可能挑到同一条
    （4 选 1，撞的概率 25%）——实测 9/22、9/23 两天的开头都是「8 点 40，开门。」，
    店员连着两天念同一句，比"AI 味"还难受。
    轮换能**保证相邻序号一定不同**（步长跟候选数互质），
    再叠一个按门店算的起点偏移，不同店同一天也不会齐刷刷一样。
    """
    return options[n % len(options)]


